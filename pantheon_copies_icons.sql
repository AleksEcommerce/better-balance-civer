-- Reuse the installed pantheons' icons on religion screens and tooltips.
INSERT OR IGNORE INTO IconDefinitions (Name, Atlas, "Index")
SELECT i.Name || '_BBC_COPY_' || n.CopyNumber, i.Atlas, i."Index"
FROM IconDefinitions i CROSS JOIN (SELECT 1 AS CopyNumber UNION ALL SELECT 2) n
WHERE i.Name IN (
